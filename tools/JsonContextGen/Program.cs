using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.CSharp.Syntax;

if (args.Length < 3)
{
    Console.Error.WriteLine("usage: JsonContextGen <sources.rsp> <references.rsp> <output.cs> [defines]");
    return 1;
}

string sourcesFile = args[0];
string referencesFile = args[1];
string outputFile = args[2];
string[] defines = args.Length > 3
    ? args[3].Split(';', StringSplitOptions.RemoveEmptyEntries | StringSplitOptions.TrimEntries)
    : [];

try
{
    string[] sources = ReadList(sourcesFile, File.Exists);
    string[] references = ReadList(referencesFile, File.Exists);

    if (sources.Length == 0)
        return 0;

    string cacheFile = outputFile + ".cache";
    string signature = BuildSignature(sources, references, defines);

    if (File.Exists(outputFile) && File.Exists(cacheFile) && File.ReadAllText(cacheFile) == signature)
        return 0;

    var parseOptions = new CSharpParseOptions(LanguageVersion.Latest, preprocessorSymbols: defines);

    var trees = new List<SyntaxTree>(sources.Length);

    foreach (string source in sources)
    {
        trees.Add(CSharpSyntaxTree.ParseText(File.ReadAllText(source), parseOptions, path: source));
    }

    var metadataReferences = new List<MetadataReference>(references.Length);

    foreach (string reference in references)
    {
        metadataReferences.Add(MetadataReference.CreateFromFile(reference));
    }

    var compilation = CSharpCompilation.Create(
        "Froststrap.AutoGenerated.JsonContext",
        trees,
        metadataReferences,
        new CSharpCompilationOptions(
            OutputKind.DynamicallyLinkedLibrary,
            nullableContextOptions: NullableContextOptions.Enable));

    INamedTypeSymbol? jsonContext = compilation.GetTypeByMetadataName("Froststrap.JsonContext");

    if (jsonContext is null)
        return 0;

    var registered = new HashSet<ITypeSymbol>(SymbolEqualityComparer.Default);

    foreach (AttributeData attribute in jsonContext.GetAttributes())
    {
        if (attribute.AttributeClass?.ToDisplayString() != "System.Text.Json.Serialization.JsonSerializableAttribute")
            continue;

        if (attribute.ConstructorArguments.Length == 1 && attribute.ConstructorArguments[0].Value is ITypeSymbol type)
            registered.Add(type);
    }

    var discovered = new Dictionary<string, ITypeSymbol>(StringComparer.Ordinal);

    foreach (SyntaxTree tree in trees)
    {
        List<InvocationExpressionSyntax> candidates = tree.GetRoot()
            .DescendantNodes()
            .OfType<InvocationExpressionSyntax>()
            .Where(IsPotentialJsonInvocation)
            .ToList();

        if (candidates.Count == 0)
            continue;

        SemanticModel model = compilation.GetSemanticModel(tree);

        foreach (InvocationExpressionSyntax invocation in candidates)
        {
            if (model.GetSymbolInfo(invocation).Symbol is not IMethodSymbol method)
                continue;

            if (method.ContainingType is not { } containing)
                continue;

            if (!JsonEntryPoints.Contains(containing.ToDisplayString()))
                continue;

            foreach (ITypeSymbol argument in method.TypeArguments)
            {
                if (argument is ITypeParameterSymbol or IErrorTypeSymbol)
                    continue;

                if (argument.SpecialType == SpecialType.System_Void)
                    continue;

                discovered[argument.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat)] = argument;
            }
        }
    }

    List<string> missing = discovered
        .Where(pair => !registered.Contains(pair.Value))
        .Select(pair => pair.Key)
        .OrderBy(name => name, StringComparer.Ordinal)
        .ToList();

    StringBuilder builder = new();
    builder.AppendLine("// <auto-generated/>");
    builder.AppendLine("// Generated by tools/JsonContextGen. Do not edit; add manual registrations to JsonContext.cs instead.");
    builder.AppendLine("#nullable enable");
    builder.AppendLine();
    builder.AppendLine("namespace Froststrap");
    builder.AppendLine("{");
    builder.AppendLine("    [global::System.Text.Json.Serialization.JsonSourceGenerationOptions(");
    builder.AppendLine("        WriteIndented = true,");
    builder.AppendLine("        ReadCommentHandling = global::System.Text.Json.JsonCommentHandling.Skip,");
    builder.AppendLine("        NumberHandling = global::System.Text.Json.Serialization.JsonNumberHandling.AllowReadingFromString)]");
    builder.AppendLine("    [global::System.Text.Json.Serialization.JsonSerializable(typeof(string))]");

    foreach (string name in missing)
    {
        builder.Append("    [global::System.Text.Json.Serialization.JsonSerializable(typeof(");
        builder.Append(name);
        builder.AppendLine("))]");
    }

    builder.AppendLine("    internal partial class JsonContextGenerated : global::System.Text.Json.Serialization.JsonSerializerContext");
    builder.AppendLine("    {");
    builder.AppendLine("    }");
    builder.AppendLine();
    builder.AppendLine("    internal static partial class JsonHelper");
    builder.AppendLine("    {");
    builder.AppendLine("        static partial void AddGeneratedResolver(ref global::System.Text.Json.Serialization.Metadata.IJsonTypeInfoResolver resolver)");
    builder.AppendLine("        {");
    builder.AppendLine("            resolver = global::System.Text.Json.Serialization.Metadata.JsonTypeInfoResolver.Combine(");
    builder.AppendLine("                resolver,");
    builder.AppendLine("                JsonContextGenerated.Default);");
    builder.AppendLine("        }");
    builder.AppendLine("    }");
    builder.AppendLine("}");

    string content = builder.ToString();

    if (File.Exists(outputFile) && File.ReadAllText(outputFile) == content)
        return 0;

    string? directory = Path.GetDirectoryName(Path.GetFullPath(outputFile));

    if (!string.IsNullOrEmpty(directory))
        Directory.CreateDirectory(directory);

    File.WriteAllText(outputFile, content);
    File.WriteAllText(cacheFile, signature);
    return 0;
}
catch (Exception ex)
{
    Console.Error.WriteLine($"JsonContextGen failed: {ex}");
    return 1;
}

static bool IsPotentialJsonInvocation(InvocationExpressionSyntax invocation)
{
    SimpleNameSyntax? name = invocation.Expression switch
    {
        MemberAccessExpressionSyntax member => member.Name,
        MemberBindingExpressionSyntax binding => binding.Name,
        SimpleNameSyntax simple => simple,
        _ => null
    };

    if (name is null)
        return false;

    string identifier = name.Identifier.ValueText;

    return identifier.Contains("Json", StringComparison.Ordinal)
        || identifier.StartsWith("Serialize", StringComparison.Ordinal)
        || identifier.StartsWith("Deserialize", StringComparison.Ordinal);
}

static string BuildSignature(IEnumerable<string> sources, IEnumerable<string> references, string[] defines)
{
    StringBuilder builder = new();

    try
    {
        string generatorPath = Path.Combine(
            AppContext.BaseDirectory,
            $"{System.Reflection.Assembly.GetEntryAssembly()?.GetName().Name ?? "JsonContextGen"}.dll");
        builder.Append(File.GetLastWriteTimeUtc(generatorPath).Ticks);
    }
    catch
    {
    }

    builder.Append('\n');
    builder.Append(string.Join(';', defines));
    builder.Append('\n');

    foreach (string path in sources.Concat(references).OrderBy(path => path, StringComparer.Ordinal))
    {
        builder.Append(path);
        builder.Append('|');

        try
        {
            builder.Append(File.GetLastWriteTimeUtc(path).Ticks);
        }
        catch
        {
        }

        builder.Append('\n');
    }

    byte[] hash = System.Security.Cryptography.SHA256.HashData(Encoding.UTF8.GetBytes(builder.ToString()));
    return Convert.ToHexString(hash);
}

static string[] ReadList(string file, Func<string, bool> filter)
    => File.Exists(file)
        ? File.ReadAllLines(file).Where(line => !string.IsNullOrWhiteSpace(line) && filter(line)).ToArray()
        : [];

internal static class JsonEntryPoints
{
    private static readonly HashSet<string> Entries = new(StringComparer.Ordinal)
    {
        "Froststrap.JsonHelper",
        "Froststrap.JsonManager",
        "Froststrap.Utility.Http",
        "Froststrap.Extensions.HttpClientEx",
        "System.Text.Json.JsonSerializer",
        "System.Net.Http.Json.HttpClientJsonExtensions",
        "System.Net.Http.Json.HttpContentJsonExtensions",
    };

    public static bool Contains(string name) => Entries.Contains(name);
}
